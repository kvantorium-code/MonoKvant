using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace AngryBirds.EditorTools.Builder
{
    /// <summary>
    /// Generates the <c>SceneName</c> enum from the scene assets in
    /// <c>Assets/AngryBirds/Scenes</c> so runtime code never uses raw scene-name strings.
    /// Running the generator again is idempotent: the file is only rewritten when the
    /// scene list changes.
    /// </summary>
    internal static class SceneNameGenerator
    {
        private const string SceneFolder = "Assets/AngryBirds/Scenes";
        private const string OutputPath = "Assets/AngryBirds/Scripts/Infrastracture/SceneName.cs";

        [MenuItem("Tools/AngryBirds/3. Generate Scene Names", false, 30)]
        public static void Generate()
        {
            string[] guids = AssetDatabase.FindAssets("t:Scene", new[] { SceneFolder });
            var entries = new List<SceneEntry>(guids.Length);

            foreach (string guid in guids)
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);

                if (!path.EndsWith(".unity", StringComparison.OrdinalIgnoreCase))
                {
                    continue;
                }

                string sceneName = Path.GetFileNameWithoutExtension(path);
                entries.Add(new SceneEntry(sceneName, MakeIdentifier(sceneName)));
            }

            entries.Sort((left, right) =>
            {
                int result = string.CompareOrdinal(left.Identifier, right.Identifier);
                return result != 0 ? result : string.CompareOrdinal(left.SceneName, right.SceneName);
            });

            EnsureUniqueIdentifiers(entries);

            string content = BuildSource(entries);

            if (File.Exists(OutputPath) && File.ReadAllText(OutputPath) == content)
            {
                return;
            }

            File.WriteAllText(OutputPath, content, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(OutputPath, ImportAssetOptions.ForceUpdate);
            Debug.Log($"[SceneNameGenerator] Generated {entries.Count} scene names in {OutputPath}.");
        }

        private static string MakeIdentifier(string sceneName)
        {
            var builder = new StringBuilder(sceneName.Length);

            foreach (char character in sceneName)
            {
                builder.Append(char.IsLetterOrDigit(character) ? character : '_');
            }

            if (builder.Length == 0)
            {
                return "Scene";
            }

            if (char.IsDigit(builder[0]))
            {
                builder.Insert(0, '_');
            }

            builder[0] = char.ToUpperInvariant(builder[0]);
            return builder.ToString();
        }

        private static void EnsureUniqueIdentifiers(List<SceneEntry> entries)
        {
            var used = new HashSet<string>(StringComparer.Ordinal);

            foreach (SceneEntry entry in entries)
            {
                string identifier = entry.Identifier;
                int suffix = 2;

                while (!used.Add(identifier))
                {
                    identifier = entry.Identifier + "_" + suffix;
                    suffix++;
                }

                entry.Identifier = identifier;
            }
        }

        private static string BuildSource(List<SceneEntry> entries)
        {
            var builder = new StringBuilder();
            builder.Append("// <auto-generated />\n");
            builder.Append("// Generated by SceneNameGenerator from the scenes in Assets/AngryBirds/Scenes.\n");
            builder.Append("namespace AngryBirds.Infrastructure\n");
            builder.Append("{\n");
            builder.Append("    public enum SceneName\n");
            builder.Append("    {\n");

            for (int i = 0; i < entries.Count; i++)
            {
                builder.Append("        ");
                builder.Append(entries[i].Identifier);
                builder.Append(" = ");
                builder.Append(i);

                if (i < entries.Count - 1)
                {
                    builder.Append(',');
                }

                builder.Append('\n');
            }

            builder.Append("    }\n");
            builder.Append('\n');
            builder.Append("    public static class SceneNameExtensions\n");
            builder.Append("    {\n");
            builder.Append("        public static string ToSceneName(this SceneName sceneName)\n");
            builder.Append("        {\n");
            builder.Append("            switch (sceneName)\n");
            builder.Append("            {\n");

            foreach (SceneEntry entry in entries)
            {
                builder.Append("                case SceneName.");
                builder.Append(entry.Identifier);
                builder.Append(": return \"");
                builder.Append(entry.SceneName.Replace("\\", "\\\\").Replace("\"", "\\\""));
                builder.Append("\";\n");
            }

            builder.Append("                default: throw new System.ArgumentOutOfRangeException(nameof(sceneName));\n");
            builder.Append("            }\n");
            builder.Append("        }\n");
            builder.Append("    }\n");
            builder.Append("}\n");
            return builder.ToString();
        }

        private sealed class SceneEntry
        {
            public SceneEntry(string sceneName, string identifier)
            {
                SceneName = sceneName;
                Identifier = identifier;
            }

            public string SceneName { get; }

            public string Identifier { get; set; }
        }
    }
}
